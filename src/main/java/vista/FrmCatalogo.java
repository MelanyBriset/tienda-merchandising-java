    private void btnGuardarProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarProductoActionPerformed
    String codigo = txtCodigo.getText().trim().toUpperCase();
String nombre = txtNombre.getText().trim();
String precioTxt = txtPrecio.getText().trim();

if (codigo.isEmpty() || nombre.isEmpty() || precioTxt.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Complete todos los campos.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
    return;
}

try {
    double precio = Double.parseDouble(precioTxt);
    int stock = Integer.parseInt(spStock.getValue().toString());

    if (precio <= 0 || stock < 0) {
        JOptionPane.showMessageDialog(this, "El precio debe ser mayor a 0 y el stock no puede ser negativo.", "Datos inválidos", JOptionPane.WARNING_MESSAGE);
        return;
    }

    boolean registrado = gestor.registrarProducto(codigo, nombre, precio, stock);

    if (registrado) {
        JOptionPane.showMessageDialog(this, "Producto registrado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
        cargarTablaCatalogo();
        limpiarCampos();
    } else {
        JOptionPane.showMessageDialog(this, "El código ya existe o los datos son inválidos.", "Error de registro", JOptionPane.ERROR_MESSAGE);
    }

} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this, "Ingrese un precio numérico válido (ej. 15.50).", "Formato incorrecto", JOptionPane.ERROR_MESSAGE);
}    // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarProductoActionPerformed


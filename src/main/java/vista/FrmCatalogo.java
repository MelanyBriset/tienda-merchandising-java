    private void configurarTabla() {
    modeloTabla = new DefaultTableModel(
        new Object[]{"Código", "Producto", "Precio Unit.", "Stock"}, 0
    ) {
        @Override
    public boolean isCellEditable(int row, int column) {
            return false;
        }
    };
    tblCatalogo.setModel(modeloTabla);
    tblCatalogo.setRowHeight(28);
}

    private void cargarTablaCatalogo() {
    modeloTabla.setRowCount(0);
    for (Producto p : gestor.getCatalogo()) {
        modeloTabla.addRow(new Object[]{
            p.getCodigo(),
            p.getNombre(),
            String.format("S/ %.2f", p.getPrecioUnitario()),
            p.getStock()
        });
    }
}

